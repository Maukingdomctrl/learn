// Copies the Tabler outline icons the cards use into engine/icons.js, so the site needs no download
// at run time and pictures stay the same every time. Run after changing the list or the Tabler version:
//   node scripts/build-icons.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Our picture name -> Tabler icon name.
const USE = {
  ship: 'ship',
  river: 'ripple',
  crown: 'crown',
  factory: 'building-factory-2',
  steam: 'train',
  plane: 'plane',
  museum: 'building-arch',
  bank: 'building-bank',
  gear: 'settings',
  people: 'users',
  jobs: 'needle-thread',
  theatre: 'masks-theater',
  castle: 'building-castle',
  parliament: 'gavel',
  coal: 'pick',
  bulb: 'bulb',
  calendar: 'calendar',
  globe: 'world',
  camera: 'camera',
  book: 'book',
  pin: 'map-pin',
  market: 'building-store',
  sport: 'ball-football',
  star: 'star',
  sword: 'swords',
  scroll: 'license',
  scales: 'scale',
  person: 'user',
  metal: 'hammer',
  crop: 'plant',
  cloth: 'shirt',
  water: 'droplet',
  transport: 'truck',
  sweet: 'candy',
  vote: 'checkbox',
  shield: 'shield-check',
  quake: 'activity',
  car: 'car',
  building: 'building',
  sun: 'sun',
  wind: 'wind',
  recycle: 'recycle',
  tree: 'trees',
  power: 'bolt',
};

const root = new URL('../', import.meta.url);
const pkg = JSON.parse(readFileSync(new URL('node_modules/@tabler/icons/package.json', root), 'utf8'));
const license = readFileSync(new URL('node_modules/@tabler/icons/LICENSE', root), 'utf8').trim();

const icons = {};
for (const [ours, theirs] of Object.entries(USE)) {
  const svg = readFileSync(new URL(`node_modules/@tabler/icons/icons/outline/${theirs}.svg`, root), 'utf8');
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
    .replace(/\s+/g, ' ')
    .trim();
  icons[ours] = inner;
}

const out = `// Generated by scripts/build-icons.mjs from @tabler/icons ${pkg.version} (outline set). Do not edit by hand.
//
${license
  .split('\n')
  .map((l) => `// ${l}`.trimEnd())
  .join('\n')}

export const TABLER_VERSION = '${pkg.version}';

export const ICONS = ${JSON.stringify(icons, null, 2)};
`;
writeFileSync(fileURLToPath(new URL('engine/icons.js', root)), out);
console.log(`wrote engine/icons.js: ${Object.keys(icons).length} icons from @tabler/icons ${pkg.version}`);
