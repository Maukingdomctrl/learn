"""Deterministic checks for visuals (D8): structure, faithful drawing, print ink, grounding, size budget.

Grounding rules apply to the text a visual actually prints: its caption, every string drawn in the SVG
(including code-generated shape labels and units), and for tables the headers and cells.
- every printed number must appear in the cited source units or in the stage's own text (so the picture matches
  the explanation and worked example beside it). Exempt: number-line tick labels (the axis), jump lengths, and a
  bar total that equals the sum of its parts;
- every content word (4+ letters, not a common function word) in the caption and labels must appear in the cited
  source units, the lesson's defined terms or its concept names. Exempt: words code writes itself (CODE_WORDS),
  a few words that describe a visual rather than make a claim (STRUCTURE_WORDS), and table column headers;
- a shape's unit must appear in the cited source units or the stage's text.
"""

import html
import re

from .specs import BarModelSpec, FlowSequenceSpec, NumberLineSpec, ShapeSpec, Table
from .svg import CHAR_MM, INK_FILLS, MAX_TICKS, bar_total, draw, flow_box_width, fmt, wrap

MAX_HEIGHT_MM = 64.0
MAX_TABLE_ROWS, MAX_TABLE_COLS, MAX_CELL_CHARS = 6, 5, 40
STOP = set(
    "about above after again also among another because been before being below between both came come could does "
    "done down each even every from have here into just like made make many more most much must near next once "
    "only other over same shall should show shows some such than that their them then there these they this those "
    "through under upon very were what when where which while will with within without would your same each "
    "step steps first second third last".split()
)

CODE_WORDS = {"base", "height", "length", "width", "radius", "scale"}  # labels generated by svg.py
STRUCTURE_WORDS = {
    "worked",
    "example",
    "diagram",
    "picture",
    "table",
    "timeline",
    "sequence",
    "cycle",
    "model",
    "number",
    "line",
    "shape",
    "compare",
    "comparison",
    "order",
    "stage",
    "part",
    "whole",
    "total",
    "label",
}

_NUM_RE = re.compile(r"[-−]?\d+(?:,\d{3})*(?:\.\d+)?(?:\s*/\s*\d+)?")


def numbers_in(text: str) -> set[float]:
    out: set[float] = set()
    for m in _NUM_RE.finditer(text or ""):
        raw = m.group(0).replace("−", "-").replace(",", "").replace(" ", "")
        if "/" in raw:
            a, b = raw.split("/")
            out.add(float(a))
            out.add(float(b))
            if float(b) != 0:
                out.add(float(a) / float(b))
        else:
            out.add(float(raw))
    return out


def _norm(word: str) -> str:
    if len(word) > 4 and word.endswith("es"):
        return word[:-2]
    if len(word) > 4 and word.endswith("s"):
        return word[:-1]
    return word


def content_words(text: str) -> set[str]:
    return {_norm(w) for w in re.findall(r"[a-z]+", (text or "").lower()) if len(w) >= 4 and w not in STOP}


def vocabulary(text: str) -> set[str]:
    return {_norm(w) for w in re.findall(r"[a-z]+", (text or "").lower())}


def svg_texts(svg: str) -> list[str]:
    return [html.unescape(t) for t in re.findall(r"<text[^>]*>(.*?)</text>", svg)]


def svg_inks(svg: str) -> tuple[set[str], set[str]]:
    return set(re.findall(r'fill="([^"]+)"', svg)), set(re.findall(r'stroke="([^"]+)"', svg))


# ---------------------------------------------------------------- what each spec must show
def drawn_numbers(v) -> list[float]:
    """Numbers the drawing shows, including numbers written inside labels (e.g. a year in a timeline step)."""
    nums = _spec_numbers(v)
    label_nums = numbers_in(" ".join(labels(v, include_headers=False))) if not isinstance(v, Table) else set()
    if isinstance(v, NumberLineSpec):  # a jump label such as "+4" may state the jump's length
        label_nums -= {abs(j.end - j.start) for j in v.jumps}
    return nums + sorted(label_nums)


def _spec_numbers(v) -> list[float]:
    if isinstance(v, ShapeSpec):
        return [n for n in (v.base, v.height, v.length, v.width, v.radius) if n is not None]
    if isinstance(v, NumberLineSpec):
        return [p.value for p in v.points] + [x for j in v.jumps for x in (j.start, j.end)]
    if isinstance(v, BarModelSpec):
        nums = [p.value for b in v.bars for p in b.parts]
        nums += [b.total for b in v.bars if b.total is not None and abs(b.total - bar_total(b)) > 1e-9]
        return nums
    if isinstance(v, Table):
        return sorted(numbers_in(" ".join(c for row in v.rows for c in row)))
    return []


def labels(v, include_headers: bool = True) -> list[str]:
    if isinstance(v, NumberLineSpec):
        return [p.label for p in v.points if p.label] + [j.label for j in v.jumps if j.label]
    if isinstance(v, BarModelSpec):
        return [b.label for b in v.bars] + [p.label for b in v.bars for p in b.parts if p.label]
    if isinstance(v, FlowSequenceSpec):
        return list(v.steps)
    if isinstance(v, Table):
        return (v.headers if include_headers else []) + [c for row in v.rows for c in row]
    return []


def expected_texts(v) -> list[str]:
    """Text the drawing must contain if it faithfully shows its spec."""
    if isinstance(v, ShapeSpec):
        unit = f" {v.unit}".rstrip() if v.unit else ""
        if v.shape == "circle":
            return [f"radius = {fmt(v.radius)}{unit}"] if v.radius else []
        b, h = ("length", "width") if v.shape == "rectangle" else ("base", "height")
        bv, hv = (v.length, v.width) if v.shape == "rectangle" else (v.base, v.height)
        return [f"{b} = {fmt(bv)}{unit}", f"{h} = {fmt(hv)}{unit}"] if bv and hv else []
    if isinstance(v, NumberLineSpec):
        return [fmt(v.start), fmt(v.end)] + labels(v)
    if isinstance(v, BarModelSpec):
        out = [b.label for b in v.bars]
        for b in v.bars:
            out += [f"{p.label} {fmt(p.value)}".strip() if p.label else fmt(p.value) for p in b.parts]
            out.append(f"= {fmt(b.total if b.total is not None else bar_total(b))}")
        return out
    if isinstance(v, FlowSequenceSpec):
        max_lines = 2 if v.layout == "cycle" else 3
        return [line for step in v.steps for line in wrap(step, _flow_chars(v))[:max_lines]]
    return []


def _flow_chars(v: FlowSequenceSpec) -> int:
    return max(1, int((flow_box_width(v) - 3) / CHAR_MM))


# ---------------------------------------------------------------- structure
def structure_problems(v) -> list[str]:
    p = []
    if isinstance(v, Table):
        if not 1 <= len(v.rows) <= MAX_TABLE_ROWS:
            p.append(f"table has {len(v.rows)} rows; allowed 1-{MAX_TABLE_ROWS}")
        cols = len(v.headers) or (len(v.rows[0]) if v.rows else 0)
        if not 1 <= cols <= MAX_TABLE_COLS:
            p.append(f"table has {cols} columns; allowed 1-{MAX_TABLE_COLS}")
        if any(len(r) != cols for r in v.rows):
            p.append("table rows do not all have the same number of cells as the header")
        if any(len(c) > MAX_CELL_CHARS for c in v.headers + [c for r in v.rows for c in r]):
            p.append(f"a table cell is longer than {MAX_CELL_CHARS} characters")
    elif isinstance(v, ShapeSpec):
        need = {"triangle": ("base", "height"), "parallelogram": ("base", "height"), "rectangle": ("length", "width")}
        names = need.get(v.shape, ("radius",))
        for name in names:
            val = getattr(v, name)
            if val is None or val <= 0:
                p.append(f"{v.shape} needs a positive {name}")
    elif isinstance(v, NumberLineSpec):
        if v.end <= v.start or v.step <= 0:
            p.append("number line needs start < end and a positive step")
        else:
            n = (v.end - v.start) / v.step
            if abs(n - round(n)) > 1e-9:
                p.append("number line step does not divide the range evenly")
            if round(n) > MAX_TICKS:
                p.append(f"number line has {round(n)} intervals; max {MAX_TICKS}")
            for val in drawn_numbers(v):
                if not v.start <= val <= v.end:
                    p.append(f"number line value {fmt(val)} is outside {fmt(v.start)}-{fmt(v.end)}")
    elif isinstance(v, BarModelSpec):
        if not 1 <= len(v.bars) <= 3:
            p.append(f"bar model has {len(v.bars)} bars; allowed 1-3")
        for b in v.bars:
            if not 1 <= len(b.parts) <= 6:
                p.append(f"bar '{b.label}' has {len(b.parts)} parts; allowed 1-6")
            if any(part.value <= 0 for part in b.parts):
                p.append(f"bar '{b.label}' has a part that is not positive")
            if b.total is not None and abs(b.total - bar_total(b)) > 1e-9:
                p.append(f"bar '{b.label}' total {fmt(b.total)} is not the sum of its parts ({fmt(bar_total(b))})")
    elif isinstance(v, FlowSequenceSpec):
        lo = 3 if v.layout == "cycle" else 2
        if not lo <= len(v.steps) <= 6:
            p.append(f"{v.layout} sequence has {len(v.steps)} steps; allowed {lo}-6")
        if any(not s.strip() for s in v.steps):
            p.append("a sequence step is empty")
    return p


def printed_texts(v, drawing) -> list[str]:
    """Everything the visual prints: caption, then the SVG's text (or a table's headers and cells)."""
    out = [v.caption] if v.caption.strip() else []
    if drawing is not None:
        out += svg_texts(drawing.svg)
    elif isinstance(v, Table):
        out += v.headers + [c for row in v.rows for c in row]
    return out


def exempt_numbers(v) -> set[float]:
    """Structural numbers code prints that are not claims: axis ticks, jump lengths, computed totals."""
    out: set[float] = set()
    if isinstance(v, NumberLineSpec) and v.step > 0 and v.end > v.start:
        out |= {v.start + i * v.step for i in range(round((v.end - v.start) / v.step) + 1)}
        out |= {abs(j.end - j.start) for j in v.jumps}
    if isinstance(v, BarModelSpec):
        out |= {bar_total(b) for b in v.bars}
    return out


def _close(n: float, pool: set[float]) -> bool:
    return any(abs(n - a) < 1e-9 for a in pool)


def check_visual(v, source_text: str, stage_text: str, vocab_text: str) -> list[str]:
    """All D8 problems for one visual. `source_text` = cited units, `stage_text` = the stage's printed text."""
    name = f"{v.kind} '{(v.caption or '')[:30]}'"
    problems = [f"{name}: {p}" for p in structure_problems(v)]
    if not v.purpose.strip():
        problems.append(f"{name}: needs a teaching purpose")
    drawing = None
    if not problems:
        drawing = draw(v)
        if drawing is not None:
            problems += [f"{name}: {p}" for p in drawing.problems]
            fills, strokes = svg_inks(drawing.svg)
            if fills - INK_FILLS or strokes - {"#000"}:
                problems.append(f"{name}: uses ink other than black outlines and white fill")
            shown = " | ".join(svg_texts(drawing.svg))
            missing = [t for t in expected_texts(v) if t not in shown]
            if missing:
                problems.append(f"{name}: drawing does not show {missing[:3]}")
            if drawing.height_mm > MAX_HEIGHT_MM + 1e-9:
                problems.append(f"{name}: {drawing.height_mm:.0f} mm tall; budget {MAX_HEIGHT_MM:.0f} mm")
    printed = printed_texts(v, drawing)
    allowed = numbers_in(source_text) | numbers_in(stage_text)
    exempt = exempt_numbers(v)
    shown = set(drawn_numbers(v)) | numbers_in(" | ".join(printed))
    ungrounded = sorted({fmt(n) for n in shown if not _close(n, allowed) and not _close(n, exempt)})
    if ungrounded:
        problems.append(f"{name}: numbers {ungrounded} are not in the cited source or the stage text")
    vocab = vocabulary(vocab_text)
    word_texts = printed
    if isinstance(v, Table):  # column headers' words are structure, not claims; their numbers are still checked
        word_texts = ([v.caption] if v.caption.strip() else []) + [c for row in v.rows for c in row]
    for text in word_texts:
        extra = sorted(content_words(text) - vocab - CODE_WORDS - STRUCTURE_WORDS)
        if extra:
            problems.append(f"{name}: text '{text[:40]}' uses words not in the cited source or terms: {extra[:4]}")
    if isinstance(v, ShapeSpec) and v.unit.strip():
        unit_words = set(re.findall(r"[a-z]+", v.unit.lower()))
        if not unit_words <= vocabulary(f"{source_text} {stage_text}"):
            problems.append(f"{name}: unit '{v.unit}' is not used in the cited source or the stage text")
    return problems
