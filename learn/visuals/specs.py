"""Visual specifications. The model fills these in; code validates them and draws them deterministically.

Every visual states its teaching `purpose` and cites the source units it is drawn from. Labels on shapes are
generated by code from the numbers, so a picture can never say something its numbers do not.
"""

from typing import Annotated, Literal, Optional, Union

from pydantic import BaseModel, ConfigDict, Discriminator, Field, Tag


class _Spec(BaseModel):
    model_config = ConfigDict(extra="ignore")
    caption: str = ""
    purpose: str = ""  # what the learner should notice; required by D8
    source_unit_ids: list[str] = Field(default_factory=list)


class Table(_Spec):
    kind: Literal["table"] = "table"
    headers: list[str] = Field(default_factory=list)
    rows: list[list[str]] = Field(default_factory=list)


class ShapeSpec(_Spec):
    """A geometric figure with code-generated dimension labels."""

    kind: Literal["shape"] = "shape"
    shape: Literal["triangle", "rectangle", "parallelogram", "circle"]
    base: Optional[float] = None  # triangle, parallelogram
    height: Optional[float] = None  # triangle, parallelogram (drawn as a dashed perpendicular)
    length: Optional[float] = None  # rectangle
    width: Optional[float] = None  # rectangle
    radius: Optional[float] = None  # circle
    unit: str = ""


class NumberPoint(BaseModel):
    value: float
    label: str = ""


class NumberJump(BaseModel):
    start: float
    end: float
    label: str = ""


class NumberLineSpec(_Spec):
    kind: Literal["number_line"] = "number_line"
    start: float
    end: float
    step: float
    points: list[NumberPoint] = Field(default_factory=list)
    jumps: list[NumberJump] = Field(default_factory=list)


class BarPart(BaseModel):
    value: float
    label: str = ""


class Bar(BaseModel):
    label: str
    parts: list[BarPart]
    total: Optional[float] = None  # if given, must equal the sum of the parts


class BarModelSpec(_Spec):
    """Part-whole (one bar) or comparison (2-3 bars on the same scale)."""

    kind: Literal["bar_model"] = "bar_model"
    bars: list[Bar]


class FlowSequenceSpec(_Spec):
    """Steps, stages or a timeline in order (linear), or a repeating cycle."""

    kind: Literal["flow_sequence"] = "flow_sequence"
    steps: list[str]
    layout: Literal["linear", "cycle"] = "linear"


def _kind(value) -> str:
    if isinstance(value, dict):
        return value.get("kind") or "table"  # lessons written before the visual engine have tables without kind
    return getattr(value, "kind", "table")


Visual = Annotated[
    Union[
        Annotated[Table, Tag("table")],
        Annotated[ShapeSpec, Tag("shape")],
        Annotated[NumberLineSpec, Tag("number_line")],
        Annotated[BarModelSpec, Tag("bar_model")],
        Annotated[FlowSequenceSpec, Tag("flow_sequence")],
    ],
    Discriminator(_kind),
]

VISUAL_KINDS = ("table", "shape", "number_line", "bar_model", "flow_sequence")
